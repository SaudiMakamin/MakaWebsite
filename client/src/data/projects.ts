export function getProjectsByFilter(filters: {
  client?: string;
  entity?: EntityType;
  sector?: string;
  category?: string;
  year?: string;
  status?: ProjectStatus;
  isOffshore?: boolean;
  isAramco?: boolean;
  isPipeline?: boolean;
  search?: string;
}): Project[] {
  return projects.filter(p => {
    if (filters.client && filters.client !== 'all' && p.client !== filters.client) return false;
    if (filters.entity && filters.entity !== ('all' as any) && p.entity !== filters.entity) return false;
    if (filters.sector && filters.sector !== 'all' && p.sector !== filters.sector) return false;
    if (filters.category && filters.category !== 'all' && p.category !== filters.category) return false;
    if (filters.status && filters.status !== ('' as any) && p.status !== filters.status) return false;
    if (filters.isOffshore !== undefined) {
      if (filters.isOffshore && !p.isOffshore) return false;
      if (!filters.isOffshore && p.isOffshore) return false;
    }
    if (filters.isAramco !== undefined) {
      if (filters.isAramco && !p.isAramco) return false;
    }
    if (filters.isPipeline !== undefined) {
      if (filters.isPipeline && !p.isPipeline) return false;
    }
    if (filters.year && filters.year !== 'all') {
      const y = parseInt(filters.year);
      if (p.yearFrom && p.yearTo && (y < p.yearFrom || y > p.yearTo)) return false;
      if (p.yearFrom && !p.yearTo && y !== p.yearFrom) return false;
    }
    if (filters.search) {
      const s = filters.search.toLowerCase();
      const match = p.title.toLowerCase().includes(s) ||
        p.client.toLowerCase().includes(s) ||
        p.location.toLowerCase().includes(s) ||
        p.description.toLowerCase().includes(s);
      if (!match) return false;
    }
    return true;
  });
}

export function getUniqueValues(field: keyof Project): string[] {
  const values = new Set<string>();
  projects.forEach(p => {
    const v = p[field];
    if (typeof v === 'string' && v) values.add(v);
  });
  return Array.from(values).sort();
}

export function getFeaturedProjects(): Project[] {
  return projects.filter(p => p.featured);
}

export function getAramcoProjects(): Project[] {
  return projects.filter(p => p.isAramco);
}

export function getPipelineProjects(): Project[] {
  return projects.filter(p => p.isPipeline);
}

export function getProjectsBySector(sector: string): Project[] {
  return projects.filter(p => p.sector === sector);
}

export function getProjectsByEntity(entity: EntityType): Project[] {
  return projects.filter(p => p.entity === entity);
}
